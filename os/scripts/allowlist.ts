/**
 * Merges the files the debug image opened in a traced VM run (BISMILLAH_TRACE=1, see
 * vm.ts) into os/mkosi/allowlist.txt, which os/mkosi/prune.py keeps in the image
 * (os/PLAN.md, OS-4). Run by os/scripts/trace.sh; the result is committed and
 * reviewed as a diff. A file a scenario missed is fixed with a new scenario step and
 * a new trace, never by adding its path by hand.
 *
 *   node os/scripts/allowlist.ts [results folder]   (default: os/out/test)
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { root } from "./vm.ts";

const results = process.argv[2] ?? join(root, "os/out/test");
const target = join(root, "os/mkosi/allowlist.txt");
/** Kept whole by prune.py, or only in the debug image. */
const NOT_LISTED = [
  /^\/etc\//,
  /^\/usr\/lib\/(modules|firmware)\//,
  /^\/var\//,
  /^\/usr\/libexec\/bismillah-(trace|debug-console)$/,
];

function traces(dir: string, found: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) traces(path, found);
    else if (name === "trace.log") found.push(path);
  }
  return found;
}

const logs = traces(results);
if (logs.length === 0) throw new Error(`no trace.log under ${results}: run os/scripts/trace.sh`);
const paths = new Set<string>();
let overflows = 0;
for (const log of logs) {
  for (const line of readFileSync(log, "latin1").split(/\r?\n/)) {
    if (line.startsWith("TRACE-OVERFLOW")) overflows++;
    const m = /^TRACE (\/.*)$/.exec(line);
    if (m?.[1] && !NOT_LISTED.some((re) => re.test(m[1] ?? ""))) paths.add(m[1]);
  }
}
if (overflows) throw new Error(`${overflows} trace overflows: events were lost, trace again`);

const before = existsSync(target)
  ? new Set(
      readFileSync(target, "utf8")
        .split("\n")
        .filter((l) => l.startsWith("/")),
    )
  : new Set<string>();
const sorted = [...paths].sort();
const commit = execFileSync("git", ["-C", root, "rev-parse", "--short", "HEAD"], {
  encoding: "utf8",
}).trim();
const scenarios = [...new Set(logs.map((l) => relative(results, l).split("/")[0]))].sort();
writeFileSync(
  target,
  [
    "# The files the system opened in the VM scenarios: generated by os/scripts/allowlist.ts",
    `# (${new Date().toISOString().slice(0, 10)}, ${commit}) from ${scenarios.join(", ")}.`,
    "# Don't edit; add a scenario step and trace again (os/scripts/trace.sh).",
    ...sorted,
    "",
  ].join("\n"),
);
const added = sorted.filter((p) => !before.has(p));
const gone = [...before].filter((p) => !paths.has(p));
console.log(
  `${target}: ${sorted.length} files (${added.length} new, ${gone.length} gone) from ${logs.length} boots`,
);
for (const p of added.slice(0, 20)) console.log(`  + ${p}`);
for (const p of gone.slice(0, 20)) console.log(`  - ${p}`);
